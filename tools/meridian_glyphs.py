# Width factors allow the wordmark and headings to stay composed, not monospaced.
NARROW=set('Iil!.,:;\'"()[]')
WIDE=set('MWmw')
def advance(ch):
    if ch==' ': return 360
    if ch in NARROW:return 390
    if ch in WIDE:return 820
    return 700

def glyph_height(ch):
    if ch.isupper() or ch.isdigit() or ch in 'İŞĞÇÖÜ':return 700
    if ch in '()[]\'"!?°':return 700
    if ch in 'bdfhkl':return 700
    if ch in 'gjpqy':return 700
    return 500
